@Composable
fun ActionButtonsSection(
    result: CanonicalResult,
    modifier: Modifier = Modifier
) {
    val context = LocalContext.current

    Column(modifier = modifier.fillMaxWidth()) {
        Text(
            text = "VERIFIED ACTIONS",
            color = Zinc400,
            fontSize = 11.sp,
            fontWeight = FontWeight.Bold,
            letterSpacing = 0.5.sp,
            modifier = Modifier.padding(horizontal = 4.dp, vertical = 8.dp)
        )

        // Render dynamic actions generated by the backend
        result.actions.forEach { action ->
            ActionButtonRow(
                action = action,
                onClick = {
                    when (action.type) {
                        ActionType.CALENDAR -> {
                            val title = action.payload["title"] ?: result.title
                            val dateText = action.payload["date"] ?: ""
                            val loc = action.payload["location"] ?: ""
                            IntentUtils.openCalendar(context, title, dateText, loc)
                        }
                        ActionType.SEARCH -> {
                            val query = action.payload["query"] ?: result.title
                            IntentUtils.openGoogleSearch(context, query)
                        }
                        ActionType.MAPS -> {
                            val query = action.payload["query"] ?: result.fields["location"]?.value.orEmpty()
                            IntentUtils.openMaps(context, query)
                        }
                        ActionType.CALL -> {
                            val phone = action.payload["phoneNumber"] ?: result.fields["phoneNumber"]?.value.orEmpty()
                            IntentUtils.dialPhone(context, phone)
                        }
                        ActionType.BROWSE -> {
                            val url = action.payload["url"] ?: result.fields["website"]?.value.orEmpty()
                            IntentUtils.openBrowser(context, url)
                        }
                        ActionType.COPY -> {
                            IntentUtils.copyToClipboard(context, result.summary)
                        }
                        ActionType.SHARE -> {
                            IntentUtils.shareResult(context, result)
                        }
                        else -> {
                            IntentUtils.openGoogleSearch(context, result.title)
                        }
                    }
                }
            )
            Spacer(modifier = Modifier.height(8.dp))
        }

        // Always provide Share and Copy if not present in actions
        Row(
            modifier = Modifier.fillMaxWidth(),
            horizontalArrangement = Arrangement.spacedBy(8.dp)
        ) {
            SecondaryActionCard(
                label = "Share",
                icon = Icons.Rounded.Share,
                onClick = { IntentUtils.shareResult(context, result) },
                modifier = Modifier.weight(1f)
            )
            SecondaryActionCard(
                label = "Copy",
                icon = Icons.Rounded.ContentCopy,
                onClick = { IntentUtils.copyToClipboard(context, result.summary) },
                modifier = Modifier.weight(1f)
            )
        }
    }
}

@Composable
private fun ActionButtonRow(
    action: ActionItem,
    onClick: () -> Unit,
    modifier: Modifier = Modifier
) {
    val shape = RoundedCornerShape(16.dp)
    val icon = when (action.type) {
        ActionType.CALENDAR -> Icons.Rounded.CalendarMonth
        ActionType.MAPS -> Icons.Rounded.Map
        ActionType.SEARCH -> Icons.Rounded.Search
        ActionType.CALL -> Icons.Rounded.Call
        ActionType.EMAIL -> Icons.Rounded.Email
        ActionType.BROWSE -> Icons.Rounded.Language
        ActionType.SHARE -> Icons.Rounded.Share
        ActionType.COPY -> Icons.Rounded.ContentCopy
    }

    Row(
        modifier = modifier
            .fillMaxWidth()
            .clip(shape)
            .background(Zinc900, shape)
            .border(1.dp, Emerald400.copy(alpha = 0.25f), shape)
            .clickable(onClick = onClick)
            .padding(16.dp),
        verticalAlignment = Alignment.CenterVertically
    ) {
        Box(
            modifier = Modifier
                .size(40.dp)
                .clip(RoundedCornerShape(10.dp))
                .background(Emerald950)
                .border(1.dp, Emerald400.copy(alpha = 0.3f), RoundedCornerShape(10.dp)),
            contentAlignment = Alignment.Center
        ) {
            Icon(
                imageVector = icon,
                contentDescription = null,
                tint = Emerald400,
                modifier = Modifier.size(20.dp)
            )
        }

        Spacer(modifier = Modifier.width(14.dp))

        Column(modifier = Modifier.weight(1f)) {
            Text(
                text = action.label,
                color = PureWhite,
                fontSize = 15.sp,
                fontWeight = FontWeight.SemiBold
            )
            Text(
                text = action.description,
                color = Zinc400,
                fontSize = 12.sp
            )
        }
    }
}

@Composable
private fun SecondaryActionCard(
    label: String,
    icon: ImageVector,
    onClick: () -> Unit,
    modifier: Modifier = Modifier
) {
    val shape = RoundedCornerShape(14.dp)
    Row(
        modifier = modifier
            .clip(shape)
            .background(Zinc900, shape)
            .border(1.dp, Zinc800, shape)
            .clickable(onClick = onClick)
            .padding(vertical = 12.dp, horizontal = 16.dp),
        verticalAlignment = Alignment.CenterVertically,
        horizontalArrangement = Arrangement.Center
    ) {
        Icon(
            imageVector = icon,
            contentDescription = null,
            tint = Zinc400,
            modifier = Modifier.size(16.dp)
        )
        Spacer(modifier = Modifier.width(6.dp))
        Text(
            text = label,
            color = PureWhite,
            fontSize = 13.sp,
            fontWeight = FontWeight.Medium
        )
    }
}
